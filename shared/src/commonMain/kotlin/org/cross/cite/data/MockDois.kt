private val CC_BY = RightsDto("Creative Commons Attribution 4.0 International", "https://creativecommons.org/licenses/by/4.0/legalcode")
private val CC0 = RightsDto("Creative Commons Zero v1.0 Universal", "https://creativecommons.org/publicdomain/zero/1.0/legalcode")
private val MIT = RightsDto("MIT License", "https://opensource.org/licenses/MIT")

private fun person(given: String, family: String, vararg affiliation: String) = CreatorDto(
    name = "$family, $given",
    nameType = "Personal",
    givenName = given,
    familyName = family,
    affiliation = affiliation.toList(),
)

private fun org(name: String) = CreatorDto(name = name, nameType = "Organizational")

private fun doiRef(doi: String, relation: String, general: String? = null) =
    RelatedIdentifierDto(doi, "DOI", relation, general)

private fun urlRef(url: String, relation: String) = RelatedIdentifierDto(url, "URL", relation)

private fun dois(
    doi: String,
    title: String,
    creators: List<CreatorDto>,
    publisher: String,
    year: Int,
    general: String,
    resourceType: String? = null,
    subjects: List<String> = emptyList(),
    abstract: String,
    rights: RightsDto? = CC_BY,
    version: String? = null,
    related: List<RelatedIdentifierDto> = emptyList(),
    citations: Int = 0,
    views: Int = 0,
    downloads: Int = 0,
) = JsonApiResourceDto(
    id = doi,
    type = "dois",
    attributes = DoiAttributesDto(
        doi = doi,
        prefix = doi.substringBefore('/'),
        suffix = doi.substringAfter('/'),
        creators = creators,
        titles = listOf(TitleDto(title, lang = "en")),
        publisher = publisher,
        publicationYear = year,
        subjects = subjects.map(::SubjectDto),
        language = "en",
        types = TypesDto(resourceTypeGeneral = general, resourceType = resourceType),
        relatedIdentifiers = related,
        version = version,
        rightsList = listOfNotNull(rights),
        descriptions = listOf(DescriptionDto(abstract, "Abstract")),
        url = "https://doi.org/$doi",
        state = "findable",
        viewCount = views,
        downloadCount = downloads,
        citationCount = citations,
    ),
)

